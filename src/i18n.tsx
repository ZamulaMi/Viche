export type DictKey = keyof typeof uk;
const dicts: Record<Lang, typeof uk> = { uk, en };

type I18nCtx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: DictKey, vars?: Record<string, string | number>) => string;
};

const Ctx = createContext<I18nCtx>({
  lang: "uk",
  setLang: () => {},
  t: (k) => k,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const s = localStorage.getItem("viche:lang");
      return s === "en" ? "en" : "uk";
    } catch {
      return "uk";
    }
  });
  useEffect(() => {
    try {
      localStorage.setItem("viche:lang", lang);
    } catch {
      /* noop */
    }
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => setLangState(l), []);
  const t = useCallback(
    (k: DictKey, vars?: Record<string, string | number>) => {
      let s: string = dicts[lang][k] ?? k;
      if (vars) for (const [key, v] of Object.entries(vars)) s = s.split(`{${key}}`).join(String(v));
      return s;
    },
    [lang]
  );
  const val = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <Ctx.Provider value={val}>{children}</Ctx.Provider>;
}

export function useI18n() {
  return useContext(Ctx);
}
